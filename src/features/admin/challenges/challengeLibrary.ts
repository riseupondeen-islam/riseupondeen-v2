/** The text users see under "Instructions" — action, completion check, reminder and sincerity note. */
export function libraryInstructions(c: LibraryChallenge): string {
  const lines = [`Today’s action: ${c.action}`, `Done when: ${c.doneWhen}`];
  if (c.reminder) lines.push(`Reminder: ${c.reminder}${c.reference ? ` (${c.reference})` : ''}`);
  lines.push(`Motivation: ${c.motivation}`);
  lines.push(SINCERITY_NOTE);
  return lines.join('\n\n');
}

