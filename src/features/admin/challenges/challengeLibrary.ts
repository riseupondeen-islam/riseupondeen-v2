/* The 30-day Daily Deen Challenge library (Admin Console).
 *
 * Thirty distinct, small daily actions — remembrance, du'a, hadith, Qur'an, salah, character,
 * family, community, gratitude, knowledge, reflection and encouragement. The admin loads them into
 * the challenge schedule (deens_challenge_schedule) and the scheduler publishes one per day.
 *
 * Accuracy rules followed here:
 *  - Every Qur'an or hadith line is marked "(meaning)" — it is a translation of the meaning, not the
 *    Arabic text — and carries its reference (sūrah:āyah, or the hadith collection and number).
 *    Only well-known, authentic narrations are used; nothing is attributed without a source.
 *  - Lines marked "Motivation" are original encouragement written for RiseUponDeen, never presented
 *    as a quotation of the Prophet ﷺ.
 *  - No reward is promised beyond what the cited text itself says.
 *  - Nothing asks a user to prove, display or compare private worship; completion is an honest,
 *    private self-check, and missing a day is never shamed.
 *
 * Field limits match firestore.rules (validDailyChallenge / validScheduleEntry):
 * title ≤ 80, description ≤ 400, instructions ≤ 1000, category ≤ 30.
 */

export interface LibraryChallenge {
  /** Stable key, used to recognise entries already loaded into the schedule. */
  key: string;
  day: number;
  title: string;
  category: string;
  /** Shown as the challenge description (≤ 400). */
  summary: string;
  /** The one simple action for the day. */
  action: string;
  /** How the user knows the challenge is done. */
  doneWhen: string;
  /** Original motivational line (not a quotation). */
  motivation: string;
  /** Optional authentic reminder, already formatted with "(meaning)". */
  reminder?: string;
  /** Source of the reminder, e.g. "Qur'an 13:28" or "Sahih al-Bukhari 6405; Sahih Muslim 2691". */
  reference?: string;
  activity: 'manual' | 'tasbih';
  /** Tasbih count for tasbih challenges (≥ 2). */
  target: number;
}

